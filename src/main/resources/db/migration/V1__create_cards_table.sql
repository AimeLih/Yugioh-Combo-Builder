CREATE TABLE cards
(
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name           VARCHAR(255) NOT NULL UNIQUE,
    description    TEXT         NOT NULL,
    type           TEXT         NOT NULL,
    weight         INTEGER      NOT NULL,
    atk            INTEGER,
    def            INTEGER,
    level          INTEGER,
    race           TEXT,
    attribute      TEXT,
    archetype      TEXT,
    scale          INTEGER,
    linkvalue      INTEGER,
    link_markers    TEXT[],
    staple         BOOLEAN,
    card_image_url TEXT
);